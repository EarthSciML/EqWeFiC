#!/usr/bin/env python3
"""Fill couplings/eqatmchem_scm.esm's tests and its base-state input library.

The met state of step S is wrfout frame S of data/eqwefic/chem170_scm/run_full_met.sh (the state after
step S, which chem_driver sees; that capture's 28 dumps shared with dumps/chem170_full_mosaic are
byte-identical, chem170_full/check_full_met.py).  The chemistry state, the chemistry inputs that stay
prescribed and every chemistry expectation are the joint column's (couplings/chem170_column.esm at
commit f0d7f56, read with `git show`, so another session's in-flight edits of that file do not leak in).

Writes
  couplings/tests/chem170met_base_state_inputs.esm  Geo's time-invariant base state (generated data):
      eta_w = ZNW, phi_b = PHB, p_b = PB, and alpha_b = (phb[k+1] - phb[k]) / ((eta_w[k] - eta_w[k+1]) mub),
      the base-state inverse density the hydrostatic base geopotential was built from (WRF does not write
      alb; with hybrid_opt = 0 module_initialize_scm_xy integrates phb from it exactly this way, and with
      this alb Geo's alpha_d is -(dphi/deta)/mu_d of the TOTAL geopotential identically)
  the `tests` of model EqAtmChemScm.

  python3 tools/fill_eqatmchem_scm_tests.py [--tol r32|orig]
"""
import collections, json, subprocess, sys
import numpy as np
from scipy.io import netcdf_file

D = '/projects/illinois/eng/cee/ctessum/ctessum/data/eqwefic'
DUMPS = f'{D}/dumps/chem170_full_met'
WRFOUT = f'{D}/chem170_full/run_met/wrfout_d01_1997-06-20_12:00:00'
ESM = 'couplings/eqatmchem_scm.esm'
BASE = 'couplings/tests/chem170met_base_state_inputs.esm'
JOINT_REV = '4725833'
T0 = 300.0
REL_MET = 1e-6
TIERS = (1e2, 1e4, 1e6, 1e8)
ABS_WIDEN = 1e9   # every absolute floor: the joint column's CBM-Z floors are 1e-14 of each species' gross loss L X, so 1e-5 L X
SKIP = f'{D}/eqatmchem_scm/skip_r32.json'   # joint assertions this coupling moves beyond the widened bound (measured, see the notes)
WIDEN = 1e4          # rel 1e-9 -> 1e-5 and every absolute floor by the same factor

# chemistry inputs the coupling now computes: dropped from the joint column's overrides
COUPLED = {'CBMZColumn.' + k for k in 'T M_air M_fix H2O rho p alt ze qc w rain gsw T_sfc rh wetflag rainflag ustar rmol z0'.split()}
COUPLED |= {'GasParticle.' + k for k in 't_k p_atm relhum rh_pc'.split()}
COUPLED |= {'AerChem.' + k for k in 'temp ptot cair rh ustar dz1'.split()}


def frame(v, name, S):
    a = np.asarray(v[name][S], dtype=float)
    return a[..., 0, 0] if a.ndim >= 2 else a


def dump(s, call):
    return json.load(open(f'{DUMPS}/esm_dump_{s}_{call}.json'))['vars']


def arr(x):
    a = np.asarray(x['data'], dtype=float)
    return a.reshape(x['shape'][::-1]).T if x['shape'] else float(a[0])


def fl(a):
    return [float(x) for x in np.asarray(a).ravel()]


def const_template(name, axis, values, desc):
    return {'params': [], 'match': {'op': name, 'args': []}, 'description': desc,
            'body': {'op': 'faq', 'output_idx': ['k'], 'args': [], 'ranges': {'k': {'from': axis}},
                     'expr': {'op': 'index', 'args': [{'op': 'const', 'args': [], 'value': fl(values)}, 'k']}}}


def write_base(v):
    znw = np.asarray(v['ZNW'][0], dtype=float)
    phb = frame(v, 'PHB', 0)
    mub = float(frame(v, 'MUB', 0))
    alb = np.diff(phb) / ((znw[:-1] - znw[1:]) * mub)
    lib = {'esm': '1.2.0',
           'metadata': {'name': 'chem170met_base_state_inputs',
                        'description': ("Base-state column of the chem_opt = 170 reference column (em_scm_xy, Kansas, 59 layers, p_top "
                                        f"{float(v['P_TOP'][0]):.6g} Pa, mub {mub:.10g} Pa) for WRFColumnGeometry's time-invariant "
                                        "rewrite targets, from wrfout frame 0 of data/eqwefic/chem170_scm/run_full_met.sh (identical in "
                                        "every frame). alpha_b is not in the history; it is recovered from the base geopotential the way "
                                        "module_initialize_scm_xy built it (hybrid_opt = 0: phb(k+1) = phb(k) - dnw(k) mub alb(k)), with "
                                        "the eta spacing Geo itself forms, so Geo's inverse dry density is exactly -(d(phb + ph)/deta)/mu_d. "
                                        "Generated by tools/fill_eqatmchem_scm_tests.py -- do not edit."),
                        'license': 'MIT', 'tags': ['test-inputs', 'generated', 'chem170']},
           'expression_templates': {
               'input_eta_w': const_template('input_eta_w', 'lev_nodes', znw, 'WRF znw.'),
               'input_phi_b': const_template('input_phi_b', 'lev_nodes', phb, 'WRF phb.'),
               'input_alpha_b': const_template('input_alpha_b', 'lev', alb, 'WRF alb, recovered from phb.'),
               'input_p_b': const_template('input_p_b', 'lev', frame(v, 'PB', 0), 'WRF pb.')}}
    with open(BASE, 'w') as f:
        json.dump(lib, f, indent=1)
        f.write('\n')


def widen(t):
    if t is None:
        return None
    out = dict(t)
    if out.get('rel', None) not in (None, 0.0):
        out['rel'] = max(out['rel'], 1e-5)
    if out.get('abs'):
        out['abs'] = out['abs'] * ABS_WIDEN
    return out


def main():
    mode = sys.argv[sys.argv.index('--tol') + 1] if '--tol' in sys.argv else 'r32'
    v = netcdf_file(WRFOUT, 'r', mmap=False).variables
    write_base(v)
    joint = json.loads(subprocess.check_output(['git', 'show', f'{JOINT_REV}:couplings/chem170_column.esm']))
    tests = []
    for jt in joint['models']['Join']['tests']:
        S = int(jt['id'].rsplit('step', 1)[1])
        k, e, wl, we, mo = (dump('cbmz_kpp', S), dump('emissions', S), dump('wetdep_ls', S),
                            dump('wesely', S - 2), dump('mosaic', S))
        po = {key: val for key, val in jt['parameter_overrides'].items() if key not in COUPLED}
        q = {n: frame(v, n, S) for n in ('QVAPOR', 'QCLOUD', 'QRAIN', 'QICE', 'QSNOW', 'QGRAUP')}
        po.update({
            'EqAtmChemScm.theta_m': fl(frame(v, 'THM', S) + T0), 'EqAtmChemScm.qv': fl(q['QVAPOR']),
            'EqAtmChemScm.qc': fl(q['QCLOUD']), 'EqAtmChemScm.qr': fl(q['QRAIN']), 'EqAtmChemScm.qi': fl(q['QICE']),
            'EqAtmChemScm.qs': fl(q['QSNOW']), 'EqAtmChemScm.qg': fl(q['QGRAUP']),
            'EqAtmChemScm.phi_p': fl(frame(v, 'PH', S)), 'EqAtmChemScm.w': fl(frame(v, 'W', S)[:-1]),
            'EqAtmChemScm.mu_p': float(frame(v, 'MU', S)), 'EqAtmChemScm.mu_b': float(frame(v, 'MUB', S)),
            'EqAtmChemScm.p_top': float(v['P_TOP'][S]), 'EqAtmChemScm.alt_wrf': fl(arr(e['alt'])),
            'EqAtmChemScm.tsk': float(arr(we['ta'])), 'EqAtmChemScm.ust': float(arr(we['ustar'])),
            'EqAtmChemScm.rmol': float(arr(we['rmol'])), 'EqAtmChemScm.znt': float(arr(we['zntt'])),
            'EqAtmChemScm.gsw': float(arr(e['gsw'])), 'EqAtmChemScm.rainncv': float(arr(wl['rain'])),
            'EqAtmChemScm.raincv': 0.0})
        # the coupled fields must equal what the joint column prescribed (checked here, not assumed)
        jpo = jt['parameter_overrides']
        assert np.array_equal(jpo['CBMZColumn.w'], po['EqAtmChemScm.w'])
        assert np.array_equal(jpo['CBMZColumn.qc'], po['EqAtmChemScm.qc'])
        assert jpo['CBMZColumn.rain'] == po['EqAtmChemScm.rainncv'] and jpo['CBMZColumn.T_sfc'] == po['EqAtmChemScm.tsk']
        assert jpo['AerChem.ustar'] == po['EqAtmChemScm.ust']
        # (i) met -> chem fields against what WRF handed the chemistry
        met = []
        def add(var, ref, rel=REL_MET, axis='lev'):
            for lev, x in enumerate(np.atleast_1d(ref), 1):
                a = {'variable': var, 'time': 0.0, 'expected': float(x), 'tolerance': {'rel': rel, 'abs': 0.0}}
                if np.ndim(ref):
                    a['coords'] = {axis: lev}
                met.append(a)
        fix = arr(k['fix'])
        add('ChemMet.T', arr(k['temp'])); add('ChemMet.rho', arr(k['rho_phy'])); add('ChemMet.M_air', arr(k['c_m']))
        add('ChemMet.H2O', fix[0]); add('Geo.p', arr(k['p_phy']), 1e-5); add('Geo.z_w', jpo['CBMZColumn.ze'], axis='lev_nodes')
        add('ChemMet.rhchem', arr(we['rhchem']), 1e-5)
        add('Host.ptot', arr(mo['ptotclm']), 1e-5); add('Host.cair', arr(mo['cairclm'])); add('Host.relhum', arr(mo['relhumclm']), 1e-5)
        add('Host.temp', jpo['AerChem.temp'])
        for f in ('wetflag', 'rainflag'):
            met.append({'variable': f'ChemMet.{f}', 'time': 0.0, 'expected': float(bool(we[f]['data'][0])),
                        'tolerance': {'rel': 0.0, 'abs': 0.0}})
        # N128: the stale alt against the column's own inverse dry density, from the frame in real64
        znw = np.asarray(v['ZNW'][S], dtype=float)
        ad = -(np.diff(frame(v, 'PHB', S) + frame(v, 'PH', S)) / np.diff(znw)) / float(frame(v, 'MUB', S) + frame(v, 'MU', S))
        dalt = arr(e['alt']) / ad - 1
        for lev, x in enumerate(dalt, 1):
            met.append({'variable': 'EqAtmChemScm.d_alt', 'coords': {'lev': lev}, 'time': 0.0, 'expected': float(x),
                        'tolerance': {'rel': 1e-3, 'abs': 1e-9}})
        # (ii) the joint column's assertions
        asr = []
        for a in jt['assertions']:
            b = dict(a)
            if mode == 'r32' and 'tolerance' in b:
                b['tolerance'] = widen(b['tolerance'])
            asr.append(b)
        dropped = collections.Counter()
        if mode == 'r32' and SKIP:
            sk = {(x['variable'], json.dumps(x['coords'], sort_keys=True), x['expected'])
                  for x in json.load(open(SKIP)).get(f'eqatmchem_scm_step{S}', [])}
            kept = []
            for b in asr:
                if (b['variable'], json.dumps(b.get('coords'), sort_keys=True), b['expected']) in sk:
                    dropped[b['variable'].split('[')[0]] += 1
                else:
                    kept.append(b)
            asr = kept
        if mode == 'tiers':   # calibration only: every joint assertion again at its tolerance x F
            base = list(asr)
            for F in TIERS:
                for a in base:
                    b = dict(a)
                    t = dict(b.get('tolerance', jt['tolerance']))
                    if t.get('rel'):
                        t['rel'] = t['rel'] * F
                    t['abs'] = t.get('abs', 0.0) * F
                    b['tolerance'] = t
                    asr.append(b)
        ttol = widen(jt['tolerance']) if mode == 'r32' else jt['tolerance']
        when = v['Times'][S].tobytes().decode()
        tests.append({
            'id': f'eqatmchem_scm_step{S}',
            'description': (f"EqAtmChem-SCM at model step {S} ({when} UTC) of the chem_opt = 170 joint column's reference run. "
                            f"MET STATE: wrfout frame {S} of data/eqwefic/chem170_scm/run_full_met.sh (THM + t0, the six moist "
                            f"species, PH, W at each layer's lower face, MU; base state from couplings/tests/chem170met_base_state_inputs.esm). "
                            f"Still prescribed from the step: alt_wrf (the emissions dump's alt, N128), tsk, ust, rmol, znt (wesely dump of call "
                            f"{S - 2} = ktau {S}), gsw (emissions dump), the step's grid-scale rain (wetdep_ls dump) and, from the joint "
                            f"column, the photolysis frequencies and every aerosol input. CHEMISTRY: the joint column's state and "
                            f"expectations, couplings/chem170_column.esm test chem170_joint_step{S} @ {JOINT_REV} (see its description). "
                            f"ASSERTED: (i) {len(met)} met -> chem fields against what WRF handed the chemistry, rel {REL_MET:g} (KPP TEMP, "
                            f"rho_phy, C_M, FIX(H2O), p_phy, z_at_w; MOSAIC's ptotclm, cairclm, relhumclm, temperature; rhchem; the flags "
                            f"exactly), and d_alt against the real64 offset of the frame (rel 1e-3); (ii) the joint column's {len(asr)} "
                            + ("assertions at their own tolerances." if mode == 'orig' else
                               f"assertions with rel raised to 1e-5 and every absolute floor scaled by {ABS_WIDEN:g} (the CBM-Z floors, 1e-14 of each species gross loss, become 1e-5 of it): the chemistry now reads "
                               "real64 recomputations of WRF's real32 meteorology instead of the real32 values the joint column's "
                               "expectations were replayed at. NOT asserted: the " + f"{sum(dropped.values())} joint assertions that this moves beyond even that bound (" + json.dumps(dict(dropped)) + "; listed in data/eqwefic/eqatmchem_scm/skip_r32.json): MTEM activity coefficients and nucleation, steep in the relative humidity, and (at the shower step) a few radicals whose net tendency cancels below 1e-5 of the gross terms. They are a measured sensitivity to real32-vs-real64 meteorology, not a disagreement in the chemistry, which the joint column pins at rel 1e-9 against the real32 inputs.") +
                            " Filled by tools/fill_eqatmchem_scm_tests.py."),
            'parameter_overrides': po,
            'initial_conditions': jt['initial_conditions'],
            'time_span': {'start': 0, 'end': 0},
            'tolerance': ttol,
            'assertions': met + asr})
    doc = json.load(open(ESM))
    doc['models']['EqAtmChemScm']['tests'] = tests
    with open(ESM, 'w') as f:
        json.dump(doc, f, indent=2)
        f.write('\n')
    for t in tests:
        print(t['id'], len(t['assertions']))


if __name__ == '__main__':
    main()
